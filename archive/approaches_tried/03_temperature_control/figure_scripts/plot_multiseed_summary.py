# ===========================================================================
# Figure 3 — Reward vs Violation Scatter, All Seeds
# ===========================================================================
def fig_reward_vs_viol(summary: dict) -> None:
    fig, ax = plt.subplots(figsize=(COL1, 2.8))

    for algo in ALGO_ORDER:
        if algo not in summary:
            continue
        color  = ALGO_COLORS[algo]
        marker = ALGO_MARKERS[algo]
        seeds  = summary[algo]["per_seed"]

        rewards = [s["reward"] for s in seeds]
        viols   = [s["violation_rate"] * 100 for s in seeds]

        ax.scatter(viols, rewards, color=color, marker=marker,
                   s=22, zorder=4, alpha=0.85, label=algo)
        # Mean marker (larger, filled, with black edge)
        ax.scatter(summary[algo]["violation_rate_mean"] * 100,
                   summary[algo]["reward_mean"],
                   color=color, marker=marker, s=60,
                   edgecolors="black", linewidths=0.6,
                   zorder=5)

    # RBC vertical line
    ax.axvline(RBC_VIOL * 100, color="#424242", linewidth=0.9,
               linestyle="--", zorder=2, label=f"RBC ({RBC_VIOL*100:.0f}%)")

    ax.set_xlabel("Comfort Violation Rate (%)")
    ax.set_ylabel("Total Episode Reward")
    ax.set_title("Reward vs. Violation Rate\n(each point = one seed; large = mean)")
    ax.legend(fontsize=6, ncol=1, loc="upper left")
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)

    save(fig, "fig_multiseed_reward_vs_viol")


