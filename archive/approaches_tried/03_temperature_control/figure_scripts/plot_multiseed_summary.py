# Figure 6 — Summary Table Figure (2-panel: viol + reward side by side)
# ===========================================================================
def fig_summary_two_panel(summary: dict) -> None:
    algos  = [a for a in ALGO_ORDER if a in summary]
    means_v = [summary[a]["violation_rate_mean"] * 100 for a in algos]
    stds_v  = [summary[a]["violation_rate_std"]  * 100 for a in algos]
    means_r = [summary[a]["reward_mean"] for a in algos]
    stds_r  = [summary[a]["reward_std"]  for a in algos]
    seeds   = [summary[a]["n_seeds"] for a in algos]
    colors  = [ALGO_COLORS[a] for a in algos]

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(COL2, 2.5))

    y = np.arange(len(algos))
    labels = [f"{a} (n={n})" for a, n in zip(algos, seeds)]

    # — Left: Violation Rate —
    ax1.barh(y, means_v, xerr=stds_v, color=colors, height=0.55, zorder=3,
             error_kw=dict(elinewidth=0.8, capsize=2.5, capthick=0.8,
                           ecolor="#333333"))
    ax1.axvline(RBC_VIOL * 100, color="#424242", linewidth=0.9,
                linestyle="--", zorder=2)
    ax1.text(RBC_VIOL * 100 + 0.5, len(algos) - 0.45,
             f"RBC {RBC_VIOL*100:.0f}%", fontsize=5.5, color="#424242")
    for i, (m, s) in enumerate(zip(means_v, stds_v)):
        ax1.text(m + s + 0.5, i, f"{m:.1f}%", va="center",
                 ha="left", fontsize=5.5, color="#333333")
    ax1.set_yticks(y)
    ax1.set_yticklabels(labels)
    ax1.set_xlabel("Violation Rate (%)")
    ax1.set_title("(a) Safety: Violation Rate")
    ax1.set_xlim(0, 120)
    ax1.invert_yaxis()
    ax1.spines["top"].set_visible(False)
    ax1.spines["right"].set_visible(False)

    # — Right: Reward —
    ax2.barh(y, means_r, xerr=stds_r, color=colors, height=0.55, zorder=3,
             error_kw=dict(elinewidth=0.8, capsize=2.5, capthick=0.8,
                           ecolor="#333333"))
    for i, (m, s) in enumerate(zip(means_r, stds_r)):
        ax2.text(max(m + s + 10, 10), i, f"{m:.0f}",
                 va="center", ha="left", fontsize=5.5, color="#333333")
    ax2.set_yticks(y)
    ax2.set_yticklabels([])
    ax2.set_xlabel("Total Episode Reward")
    ax2.set_title("(b) Efficiency: Episode Reward")
    ax2.invert_yaxis()
    ax2.spines["top"].set_visible(False)
    ax2.spines["right"].set_visible(False)

    fig.suptitle(
        "Multi-Seed Evaluation Summary: Mean ± Std over Best Checkpoints",
        fontsize=8.5, y=1.01
    )
    fig.tight_layout(w_pad=1.5)
    save(fig, "fig_multiseed_summary_two_panel")


