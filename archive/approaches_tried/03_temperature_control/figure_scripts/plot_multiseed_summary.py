COL1 = 3.5
COL2 = 7.16

BASE = Path("/home/extra-storage/THESIS/Safe-CityLearn-Fork/Safe-CityLearn-Fork")
FIG_DIR = BASE / "docs" / "temperature_case_study" / "figures"
FIG_DIR.mkdir(parents=True, exist_ok=True)
SUMMARY_JSON = BASE / "runs" / "multiseed_eval_summary.json"

# ---------------------------------------------------------------------------
# Colors / markers
# ---------------------------------------------------------------------------
ALGO_COLORS = {
    "CSAC-LB": "#c0392b",
    "CPO":     "#2471a3",
    "SAC-Lag": "#795548",
    "CUP":     "#e67e22",
    "FOCOPS":  "#27ae60",
}
ALGO_MARKERS = {
    "CSAC-LB": "o",
    "CPO":     "s",
    "SAC-Lag": "P",
    "CUP":     "^",
    "FOCOPS":  "D",
}
# Display order for bars (best safety first)
ALGO_ORDER = ["CSAC-LB", "SAC-Lag", "CPO", "CUP", "FOCOPS"]

RBC_VIOL = 0.516   # Cooling RBC violation rate (deterministic baseline)

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
def load_summary() -> dict:
    with open(SUMMARY_JSON) as f:
        return json.load(f)

def save(fig, stem: str) -> None:
    for ext in ("pdf", "png"):
        fig.savefig(FIG_DIR / f"{stem}.{ext}")
    plt.close(fig)
    print(f"  -> {stem}.pdf/.png")


# ===========================================================================
# Figure 1 — Mean±Std Violation Rate, All Algorithms (horizontal bar)
# ===========================================================================
def fig_multiseed_viol(summary: dict) -> None:
    algos = [a for a in ALGO_ORDER if a in summary]
    means  = [summary[a]["violation_rate_mean"] * 100 for a in algos]
    stds   = [summary[a]["violation_rate_std"]  * 100 for a in algos]
    seeds  = [summary[a]["n_seeds"] for a in algos]
    colors = [ALGO_COLORS[a] for a in algos]

    fig, ax = plt.subplots(figsize=(COL1, 2.5))

    # Horizontal bars
    y = np.arange(len(algos))
    bars = ax.barh(y, means, xerr=stds, color=colors,
                   error_kw=dict(elinewidth=0.8, capsize=2.5, capthick=0.8,
                                 ecolor="#333333"),
                   height=0.55, zorder=3)

    # RBC dashed line
    ax.axvline(RBC_VIOL * 100, color="#424242", linewidth=0.9,
               linestyle="--", zorder=2, label=f"Cooling RBC ({RBC_VIOL*100:.1f}%)")

    # Annotations: mean% (n=k)
    for i, (m, s, n) in enumerate(zip(means, stds, seeds)):
        label = f"{m:.1f}% (n={n})"
        ax.text(m + s + 0.5, i, label, va="center", ha="left",
                fontsize=5.5, color="#333333")

    ax.set_yticks(y)
    ax.set_yticklabels([f"{a}" for a in algos])
    ax.set_xlabel("Comfort Violation Rate (%)")
    ax.set_title("Multi-Seed Violation Rate: Mean ± Std (Best Checkpoint)")
    ax.set_xlim(0, 115)
    ax.invert_yaxis()
    ax.legend(loc="lower right", fontsize=6)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)

    save(fig, "fig_multiseed_all_algos_viol")


