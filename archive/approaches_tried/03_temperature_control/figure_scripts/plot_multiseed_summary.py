# Figure 7 — CSAC-LB 6-Seed Detailed Breakdown
# ===========================================================================
def fig_csaclb_six_seeds(summary: dict) -> None:
    if "CSAC-LB" not in summary:
        return

    data   = summary["CSAC-LB"]["per_seed"]
    seeds  = [int(d["seed"]) for d in data]
    viols  = [d["violation_rate"] * 100 for d in data]
    costs  = [d["cost"] for d in data]
    rewards= [d["reward"] for d in data]

    fig, axes = plt.subplots(1, 3, figsize=(COL2, 2.0))
    color = ALGO_COLORS["CSAC-LB"]

    metrics = [
        (viols,   "Violation Rate (%)", "(a)"),
        (costs,   "Total Cost",         "(b)"),
        (rewards, "Total Reward",       "(c)"),
    ]

    for ax, (vals, ylabel, title) in zip(axes, metrics):
        ax.bar(range(len(seeds)), vals, color=color, width=0.55,
               edgecolor="white", linewidth=0.4, zorder=3)
        mu = np.mean(vals)
        ax.axhline(mu, color="#555", linewidth=0.8, linestyle="--",
                   label=f"Mean={mu:.1f}")
        ax.set_xticks(range(len(seeds)))
        ax.set_xticklabels([f"s{s}" for s in seeds], fontsize=6.5)
        ax.set_ylabel(ylabel, fontsize=7)
        ax.set_title(title, fontsize=8)
        ax.legend(fontsize=5.5, loc="upper right")
        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)

        # Annotate bar tops
        for i, v in enumerate(vals):
            ax.text(i, v + 0.01 * max(vals), f"{v:.1f}",
                    ha="center", va="bottom", fontsize=5.5)

    fig.suptitle("CSAC-LB: Results Across 6 Random Seeds", fontsize=9)
    fig.tight_layout()
    save(fig, "fig_csaclb_six_seeds")


