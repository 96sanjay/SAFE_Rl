# Figure 5 — Per-Seed Dot Plot (violation rate), All Algorithms
# ===========================================================================
def fig_seed_dots(summary: dict) -> None:
    """
    Dot plot showing each seed's violation rate alongside the mean (diamond).
    Arranged as a grouped horizontal strip chart, one row per algorithm.
    """
    algos = [a for a in ALGO_ORDER if a in summary]

    fig, ax = plt.subplots(figsize=(COL2, 2.2))

    y_pos   = {a: i for i, a in enumerate(reversed(algos))}
    jitter  = np.random.default_rng(42)

    for algo in algos:
        yc     = y_pos[algo]
        color  = ALGO_COLORS[algo]
        seeds  = summary[algo]["per_seed"]
        viols  = [s["violation_rate"] * 100 for s in seeds]
        j      = jitter.uniform(-0.12, 0.12, size=len(viols))

        # Individual seeds
        ax.scatter(viols, np.full(len(viols), yc) + j,
                   color=color, s=18, alpha=0.75, zorder=4,
                   marker=ALGO_MARKERS[algo])
        # Mean diamond
        mu = summary[algo]["violation_rate_mean"] * 100
        ax.scatter([mu], [yc], color=color, marker="D",
                   s=45, zorder=5, edgecolors="black", linewidths=0.7)
        # Std whisker
        sd = summary[algo]["violation_rate_std"] * 100
        ax.plot([mu - sd, mu + sd], [yc, yc],
                color=color, linewidth=1.2, solid_capstyle="round", zorder=3)

    # RBC line
    ax.axvline(RBC_VIOL * 100, color="#424242", linewidth=0.9,
               linestyle="--", zorder=2)
    ax.text(RBC_VIOL * 100 + 0.4, len(algos) - 0.5,
            f"RBC\n{RBC_VIOL*100:.1f}%", fontsize=6,
            va="top", color="#424242")

    ax.set_yticks(list(y_pos.values()))
    ax.set_yticklabels(list(reversed(algos)))
    ax.set_xlabel("Comfort Violation Rate (%, best checkpoint)")
    ax.set_title("Per-Seed Violation Rates  ◆ = Mean  — = ±1 Std")
    ax.set_xlim(-2, 115)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)

    # Legend for markers
    handles = [
        mpatches.Patch(color=ALGO_COLORS[a], label=f"{a} (n={summary[a]['n_seeds']})")
        for a in algos if a in summary
    ]
    ax.legend(handles=handles, fontsize=6, ncol=3,
              loc="lower right", framealpha=0.9)

    save(fig, "fig_multiseed_seed_dots")


